"""Write the Unicode property tables the TypeScript port cannot get from the JS engine.

``fold`` has to give the same answer in both languages, and JavaScript has no canonical
combining class and no full case folding. Both are taken from this interpreter's
``unicodedata``, so the TypeScript side folds exactly as the Python reference does, whatever
Unicode version the browser's engine ships. Run as ``python -m conformance.unicode_tables``;
``test_conformance`` fails when the checked-in file is stale.
"""

from __future__ import annotations

import json
import sys
import unicodedata
from collections.abc import Callable, Iterator
from pathlib import Path

__all__ = ["TARGET", "render"]

TARGET = Path(__file__).resolve().parents[2] / "js" / "src" / "unicode-data.ts"


def _ranges(pred: Callable[[int], bool]) -> Iterator[tuple[int, int]]:
    start: int | None = None
    for cp in range(sys.maxunicode + 1):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            yield start, cp - 1
            start = None
    if start is not None:
        yield start, sys.maxunicode


def _flat(pred: Callable[[int], bool]) -> str:
    """Inclusive ranges as a string: base-36 gaps between successive boundaries, comma-joined.

    Each range is ``start - previous end`` then ``end - start``, which keeps the numbers small
    and the module a few kilobytes; ``unpack`` in ``js/src/unicode.ts`` reverses it.
    """
    out: list[str] = []
    last = 0
    for a, b in _ranges(pred):
        out += [_b36(a - last), _b36(b - a)]
        last = b
    return '"' + ",".join(out) + '"'


def _b36(n: int) -> str:
    digits = "0123456789abcdefghijklmnopqrstuvwxyz"
    text = ""
    while True:
        n, r = divmod(n, 36)
        text = digits[r] + text
        if n == 0:
            return text


def _is_surrogate(cp: int) -> bool:
    return 0xD800 <= cp <= 0xDFFF


def _casefold() -> tuple[str, str]:
    """``str.casefold()`` for every code point it changes, in two parts.

    Single code point folds as runs, ``gap,count,stride,delta`` in base 36 (``delta`` signed):
    from ``previous end + gap``, ``count`` code points ``stride`` apart, each folding to itself
    plus ``delta``. Upper/lower pairs alternate with stride 2 and delta 1, whole alphabets run
    with stride 1, so 1,500 mappings pack into a few hundred runs. Folds to several code points
    (``ß`` to ``ss``) are listed whole. Nothing is left to the engine's ``toLowerCase``, whose
    Unicode version is the browser's, not this interpreter's.
    """
    single: list[tuple[int, int]] = []
    multi: dict[str, str] = {}
    for cp in range(sys.maxunicode + 1):
        if _is_surrogate(cp) or (folded := chr(cp).casefold()) == chr(cp):
            continue
        if len(folded) == 1:
            single.append((cp, ord(folded) - cp))
        else:
            multi[chr(cp)] = folded
    runs: list[str] = []
    last = 0
    i = 0
    while i < len(single):
        cp, delta = single[i]
        stride, count = 1, 1
        if i + 1 < len(single) and single[i + 1][1] == delta and single[i + 1][0] - cp in (1, 2):
            stride = single[i + 1][0] - cp
            while i + count < len(single) and single[i + count] == (cp + count * stride, delta):
                count += 1
        sign = "-" if delta < 0 else ""
        runs.append(f"{_b36(cp - last)},{_b36(count)},{stride},{sign}{_b36(abs(delta))}")
        last = cp + (count - 1) * stride
        i += count
    return '"' + ";".join(runs) + '"', json.dumps(multi, ensure_ascii=True)


def render() -> str:
    """The generated module's source."""
    return "\n".join(
        [
            "// Generated by tests/conformance/unicode_tables.py from Python's unicodedata"
            f" {unicodedata.unidata_version}.",
            "// Do not edit: run `poetry run python -m conformance.unicode_tables` (from tests/).",
            "",
            f'export const UNICODE_VERSION = "{unicodedata.unidata_version}";',
            "",
            "/** `str.isspace()`: packed ranges (see `_flat`). */",
            f"export const SPACE: string = {_flat(lambda c: chr(c).isspace())};",
            "",
            "/** Canonical combining class not 0 (`unicodedata.combining`): packed ranges. */",
            "export const COMBINING: string = "
            f"{_flat(lambda c: unicodedata.combining(chr(c)) != 0)};",
            "",
            "/** Categories Cf, Cc, Zl, Zp: what `fold` drops as invisible. Packed ranges. */",
            "export const INVISIBLE: string = "
            + _flat(
                lambda c: (
                    not _is_surrogate(c)
                    and unicodedata.category(chr(c)) in {"Cf", "Cc", "Zl", "Zp"}
                )
            )
            + ";",
            "",
            "/** `str.casefold()` to one code point: runs (see `_casefold`). */",
            f"export const CASEFOLD: string = {_casefold()[0]};",
            "",
            "/** `str.casefold()` to several code points, by code point. */",
            f"export const CASEFOLD_MULTI: Readonly<Record<string, string>> = {_casefold()[1]};",
            "",
            "/** Letters and numbers (`str.isalnum()`, categories L* and N*): packed ranges. */",
            "export const ALNUM: string = "
            f"{_flat(lambda c: not _is_surrogate(c) and chr(c).isalnum())};",
            "",
            "/** Decimal digits (`unicodedata.decimal`), runs of ten from 0 to 9: packed ranges. */",
            "export const DIGITS: string = "
            + _flat(lambda c: not _is_surrogate(c) and unicodedata.decimal(chr(c), -1) >= 0)
            + ";",
            "",
        ]
    )


if __name__ == "__main__":
    TARGET.write_text(render(), encoding="utf-8")
